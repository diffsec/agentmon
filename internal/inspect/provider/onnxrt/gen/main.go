// Command gen-ort-api extracts the OrtApi struct member order from
// onnxruntime_c_api.h and writes it as Go constants.
//
// The OrtApi struct is a table of function pointers with no names at runtime:
// calling a function means indexing into it. The indices are therefore
// load-bearing and invisible when wrong -- an off-by-one calls a different
// function with the wrong arguments, which crashes at best. Hand-counting 414
// members is not something to do twice, so this reads the header.
//
// Usage:
//
//	go run ./internal/inspect/provider/onnxrt/gen \
//	  -header /path/to/onnxruntime_c_api.h \
//	  -out internal/inspect/provider/onnxrt/api_indices.go
package main

import (
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

// wanted lists the members the binding actually calls. Emitting all 414 would
// bury the ones that matter and invite use of API surface nobody has tested.
var wanted = []string{
	"GetErrorMessage",
	"CreateEnv",
	"CreateSession",
	"CreateSessionFromArray",
	"Run",
	"CreateSessionOptions",
	"SetIntraOpNumThreads",
	"SetSessionGraphOptimizationLevel",
	"CreateTensorWithDataAsOrtValue",
	"GetTensorMutableData",
	"GetTensorTypeAndShape",
	"GetDimensionsCount",
	"GetDimensions",
	"CreateCpuMemoryInfo",
	"SessionGetInputCount",
	"SessionGetOutputCount",
	"SessionGetInputName",
	"SessionGetOutputName",
	"GetAllocatorWithDefaultOptions",
	"AllocatorFree",
	"ReleaseStatus",
	"ReleaseEnv",
	"ReleaseSession",
	"ReleaseSessionOptions",
	"ReleaseValue",
	"ReleaseMemoryInfo",
	"ReleaseTensorTypeAndShapeInfo",
}

// memberRe matches the three shapes a member declaration takes: the
// ORT_API2_STATUS macro, the ORT_CLASS_RELEASE macro, and a bare function
// pointer.
var memberRe = regexp.MustCompile(`ORT_API2_STATUS\(\s*(\w+)|ORT_CLASS_RELEASE\(\s*(\w+)\s*\)|\(\s*ORT_API_CALL\s*\*\s*(\w+)\s*\)`)

var (
	blockComment = regexp.MustCompile(`(?s)/\*.*?\*/`)
	lineComment  = regexp.MustCompile(`//[^\n]*`)
)

func main() {
	header := flag.String("header", "", "path to onnxruntime_c_api.h")
	out := flag.String("out", "", "path to write the generated Go file")
	flag.Parse()
	if *header == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "both -header and -out are required")
		os.Exit(2)
	}

	src, err := os.ReadFile(*header)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	names, version, err := parse(string(src))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	index := map[string]int{}
	for i, n := range names {
		// First occurrence wins: a name appearing twice would mean the
		// header changed shape in a way this parser does not understand.
		if _, dup := index[n]; !dup {
			index[n] = i
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by ./internal/inspect/provider/onnxrt/gen. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n// Source: onnxruntime_c_api.h, ORT_API_VERSION %d, %d members.\n\n", version, len(names))
	fmt.Fprintf(&b, "package onnxrt\n\n")
	fmt.Fprintf(&b, "// apiVersion is the OrtApi version these indices were taken from.\n")
	fmt.Fprintf(&b, "//\n// GetApi returns NULL for a version the library does not implement, which\n")
	fmt.Fprintf(&b, "// is how an older runtime is refused. Indices must never be used against a\n")
	fmt.Fprintf(&b, "// different version: the struct is append-only, so an older one has the\n")
	fmt.Fprintf(&b, "// same prefix, but nothing guarantees that for a version we did not read.\n")
	fmt.Fprintf(&b, "const apiVersion = %d\n\n", version)
	fmt.Fprintf(&b, "// OrtApi member indices.\nconst (\n")

	missing := []string{}
	sorted := append([]string(nil), wanted...)
	sort.Slice(sorted, func(i, j int) bool { return index[sorted[i]] < index[sorted[j]] })
	for _, name := range sorted {
		i, ok := index[name]
		if !ok {
			missing = append(missing, name)
			continue
		}
		fmt.Fprintf(&b, "\tidx%s = %d\n", name, i)
	}
	fmt.Fprintf(&b, ")\n")

	if len(missing) > 0 {
		fmt.Fprintf(os.Stderr, "header does not declare: %s\n", strings.Join(missing, ", "))
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s: %d members, ORT_API_VERSION %d\n", *out, len(names), version)
}

// parse returns the OrtApi members in declaration order plus ORT_API_VERSION.
func parse(src string) ([]string, int, error) {
	var version int
	if m := regexp.MustCompile(`#define ORT_API_VERSION (\d+)`).FindStringSubmatch(src); m != nil {
		fmt.Sscanf(m[1], "%d", &version)
	}
	if version == 0 {
		return nil, 0, fmt.Errorf("header does not define ORT_API_VERSION")
	}

	start := strings.Index(src, "struct OrtApi {")
	if start < 0 {
		return nil, 0, fmt.Errorf("header does not contain struct OrtApi")
	}
	end := strings.Index(src[start:], "\n};")
	if end < 0 {
		return nil, 0, fmt.Errorf("struct OrtApi is not terminated")
	}

	// Comments are stripped first: the header documents members inside
	// comment blocks using the same macros, and counting those would shift
	// every index after the first one.
	body := src[start : start+end]
	body = blockComment.ReplaceAllString(body, "")
	body = lineComment.ReplaceAllString(body, "")

	var names []string
	for _, m := range memberRe.FindAllStringSubmatch(body, -1) {
		switch {
		case m[1] != "":
			names = append(names, m[1])
		case m[2] != "":
			names = append(names, "Release"+m[2])
		default:
			names = append(names, m[3])
		}
	}
	if len(names) == 0 {
		return nil, 0, fmt.Errorf("no OrtApi members found; the header shape changed")
	}
	return names, version, nil
}
